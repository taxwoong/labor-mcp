def annual_leave_days(service_years: int) -> int:
    """만 N년 근속 후 발생하는 연차일수 (80% 이상 출근 전제).
    3년 이상 근속 시 최초 1년 초과 매 2년당 1일 가산 (§60④)."""
    if service_years < 1:
        return 0
    return min(ANNUAL_LEAVE_BASE + max(0, (service_years - 1) // 2), ANNUAL_LEAVE_MAX)

