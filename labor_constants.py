def minimum_wage(year: int) -> int:
    """해당 연도 최저임금 시급. 테이블에 없는 연도는 명시적 오류 —
    조용히 최신값을 쓰면 위반 판정이 통째로 틀어지므로 갱신을 강제한다."""
    if year not in MINIMUM_WAGE:
        known = ", ".join(str(y) for y in sorted(MINIMUM_WAGE))
        raise ValueError(
            f"{year}년 최저임금이 파라미터 테이블에 없습니다 (보유: {known}). "
            f"labor_constants.MINIMUM_WAGE에 고시 값을 추가하세요 (매년 8월 초 고시).")
    return MINIMUM_WAGE[year]

